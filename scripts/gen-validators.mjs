#!/usr/bin/env node
// The schema's validators, compiled ahead of time (Ajv's standalone code) and bundled with Ajv's runtime helpers into
// one self-contained module, so the page never compiles code at run time: its Content-Security-Policy has no
// 'unsafe-eval'. Run after the schema changes (npm run update-assets); scripts/build.mjs runs it on every build.
// Writes src/schema/validators.generated.js (default export: { validateSchema, validateNode }).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(readFileSync(join(ROOT, "src", "schema", "schema.json"), "utf8"));
// The same options as src/schema/ajv.ts had at run time.
const ajv = new Ajv2020({ allErrors: true, strict: false, allowUnionTypes: true, code: { source: true } });
addFormats(ajv);
ajv.addKeyword({ keyword: "x-enumDescriptions", schemaType: "object" });
ajv.addSchema(schema);
const code = standaloneCode(ajv, { validateSchema: schema.$id, validateNode: `${schema.$id}#/$defs/node` });
// Ajv's code goes to esbuild as a virtual module: no temporary file, so the bundle names it the same on every build
// and on every machine (the file is committed, and a build must not change it).
const virtual = {
  name: "graph-validators",
  setup(b) {
    b.onResolve({ filter: /^graph-validators$/ }, () => ({ path: "validators.cjs", namespace: "graph-validators" }));
    b.onLoad({ filter: /.*/, namespace: "graph-validators" }, () => ({ contents: code, loader: "js", resolveDir: ROOT }));
  },
};
const out = await build({ stdin: { contents: `import v from "graph-validators"; export default v;`, resolveDir: ROOT, loader: "js" }, bundle: true, format: "esm", platform: "neutral", mainFields: ["main"], nodePaths: [join(ROOT, "node_modules")], write: false, legalComments: "none", plugins: [virtual] });
writeFileSync(join(ROOT, "src", "schema", "validators.generated.js"), `// Generated by scripts/gen-validators.mjs from schema.json: do not edit.\n/* eslint-disable */\n${out.outputFiles[0].text}`);
console.log("validators generated from schema.json");
